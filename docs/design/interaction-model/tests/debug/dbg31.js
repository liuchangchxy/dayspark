const path = require('path');
const { chromium } = require('playwright-core');
const CHROME = '/Users/chang/Library/Caches/ms-playwright/chromium-1243/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing';
const URL = 'file://' + path.resolve(__dirname, '..', '..', 'index.html');
(async () => {
  const b = await chromium.launch({ executablePath: CHROME });
  const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
  await p.goto(URL);
  await p.waitForFunction(() => window.__READY__);
  const day = await p.evaluate(() => { const e = window.Store.state.events.find((x) => x.rrule); return e.startDt.getTime(); });
  await p.evaluate((ms) => { window.Store.state.calendarAnchor = new Date(new Date(ms).getFullYear(), new Date(ms).getMonth(), new Date(ms).getDate()); window.Store.state.calendarFocusDay = window.Store.state.calendarAnchor; window.Store.state.calendarView = 'day'; window.App.go('calendar'); }, day);
  await p.waitForTimeout(450);
  const blocks = await p.$$eval('[data-testid="event-block"]', (ns) => ns.map((n) => ({ id: n.dataset.id, t: n.textContent.slice(0, 30) })));
  console.log('blocks', blocks);
  const box = await p.evaluate(() => { const r = document.querySelector('[data-testid="event-block"]').getBoundingClientRect(); return { x: Math.round(r.x + r.width / 2), y: Math.round(r.y + 6) }; });
  await p.mouse.move(box.x, box.y);
  await p.mouse.down();
  await p.mouse.move(box.x, box.y + 60, { steps: 8 });
  await p.mouse.up();
  await p.waitForTimeout(350);
  console.log('scope sheet', await p.evaluate(() => !!document.querySelector('.sheet')));
  const opts = await p.$$eval('.sheet .slot-sheet-option', (ns) => ns.map((n) => n.textContent.trim()));
  console.log('opts', opts);
  await p.evaluate(() => { document.querySelectorAll('.sheet .slot-sheet-option')[0].click(); });
  await p.waitForTimeout(400);
  console.log('toast', await p.evaluate(() => (document.querySelector('#toast .toast') || {}).textContent));
  const st = await p.evaluate(() => ({ events: window.Store.state.events.length, ex: window.Store.state.events.filter((e) => e.exdates && e.exdates.length).map((e) => e.summary) }));
  console.log(st);
  await p.evaluate(() => { const u = document.querySelector('#toast .undo'); u && u.click(); });
  await p.waitForTimeout(300);
  console.log('after undo', await p.evaluate(() => ({ events: window.Store.state.events.length, ex: window.Store.state.events.filter((e) => e.exdates && e.exdates.length).length })));
  await b.close();
})();
