const path = require('path');
const { chromium } = require('playwright-core');
const CHROME = '/Users/chang/Library/Caches/ms-playwright/chromium-1243/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing';
const URL = 'file://' + path.resolve(__dirname, '..', '..', 'index.html');
(async () => {
  const b = await chromium.launch({ executablePath: CHROME });
  const p = await b.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 });
  await p.goto(URL);
  await p.waitForFunction(() => window.__READY__);
  await p.evaluate(() => {
    window.Store.state.theme = 'dark';
    window.Store.applyTheme();
    window.App.go('todos');
  });
  await p.waitForTimeout(300);
  await p.screenshot({ path: '/tmp/g0-dark-todos.png' });
  await p.evaluate(() => { window.Store.state.theme = 'light'; window.Store.applyTheme(); });
  const m = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  await m.goto(URL);
  await m.waitForFunction(() => window.__READY__);
  await m.evaluate(() => window.App.openComposer('todo', {}));
  await m.waitForTimeout(300);
  await m.screenshot({ path: '/tmp/g0-m-composer.png' });
  await m.evaluate(() => window.App.back());
  await m.waitForTimeout(200);
  await m.evaluate(() => window.App.go('calendar'));
  await m.waitForTimeout(400);
  await m.screenshot({ path: '/tmp/g0-m-calendar.png' });
  await b.close();
})();
